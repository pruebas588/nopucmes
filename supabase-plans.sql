-- Tabla de la lista de planes de «Our Dates».
-- Pégalo en Supabase → SQL Editor y ejecútalo una vez.

create table if not exists public.plans (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 120),
  done boolean not null default false,
  created_by text,
  created_at timestamptz not null default now()
);

alter table public.plans enable row level security;

-- IMPORTANTE: estas políticas dejan leer y escribir con la clave pública.
-- Antes de ejecutarlas, revisa las políticas que tienes en «proposals» y ajusta estas
-- para que tengan el mismo nivel de acceso.
create policy "plans_select" on public.plans for select using (true);
create policy "plans_insert" on public.plans for insert with check (true);
create policy "plans_update" on public.plans for update using (true) with check (true);
create policy "plans_delete" on public.plans for delete using (true);
